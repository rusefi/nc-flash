def dis(path, start, stop, objdump):
    return subprocess.check_output(
        [objdump, "-D", "-b", "binary", "-m", "sh2e", "-EB",
         f"--start-address={start}", f"--stop-address={stop}", str(path)],
        text=True,
    ).replace(str(ROOT) + "/", "")


def refs(data, target):
    pools = {a for a in range(0, len(data)-3, 4)
             if struct.unpack_from(">I", data, a)[0] == target}
    users = []
    for addr in range(0, len(data)-1, 2):
        opcode = struct.unpack_from(">H", data, addr)[0]
        if opcode >> 12 == 13 and ((addr+4) & ~3) + (opcode & 255)*4 in pools:
            users.append(addr)
    return sorted(pools), users


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--objdump", default=os.environ.get("SH_OBJDUMP", "sh4-linux-gnu-objdump"))
    parser.add_argument("rom", choices=[*ROMS, "excerpts"])
    parser.add_argument("mode", nargs="?", choices=["refs", "dis"])
    parser.add_argument("addresses", nargs="*", type=lambda v: int(v, 16))
    args = parser.parse_args()
    if args.rom == "excerpts":
        for name, ranges in EXCERPTS.items():
            for start, stop in ranges:
                print("\n".join(line.rstrip() for line in
                                dis(ROMS[name], start, stop, args.objdump).splitlines()).strip())
    elif args.mode == "refs" and args.addresses:
        for target in args.addresses:
            pools, users = refs(ROMS[args.rom].read_bytes(), target)
            print(hex(target), "pools", [hex(a) for a in pools],
                  "candidate users", [hex(a) for a in users])
    elif args.mode == "dis" and len(args.addresses) == 2:
        print(dis(ROMS[args.rom], *args.addresses, args.objdump))
    else:
        parser.error("use excerpts, ROM refs ADDRESS..., or ROM dis START STOP")


if __name__ == "__main__":
    main()
